#!/usr/bin/env bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<EOSQL
CREATE ROLE iot_rw NOLOGIN;
CREATE ROLE svc_nextcloud WITH LOGIN PASSWORD '${SVC_NEXTCLOUD_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE svc_immich WITH LOGIN PASSWORD '${SVC_IMMICH_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE svc_forgejo WITH LOGIN PASSWORD '${SVC_FORGEJO_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE svc_iot_bridge WITH LOGIN PASSWORD '${SVC_IOT_BRIDGE_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE IN ROLE iot_rw;
CREATE ROLE vault_admin WITH LOGIN PASSWORD '${VAULT_DB_ADMIN_PASSWORD}' CREATEROLE NOSUPERUSER NOCREATEDB;

CREATE DATABASE nextcloud OWNER svc_nextcloud;
CREATE DATABASE immich OWNER svc_immich;
CREATE DATABASE forgejo OWNER svc_forgejo;
CREATE DATABASE iot_bridge OWNER pgadmin_priv;

REVOKE ALL ON DATABASE nextcloud FROM PUBLIC;
REVOKE ALL ON DATABASE immich FROM PUBLIC;
REVOKE ALL ON DATABASE forgejo FROM PUBLIC;
REVOKE ALL ON DATABASE iot_bridge FROM PUBLIC;
GRANT CONNECT ON DATABASE iot_bridge TO iot_rw;
GRANT CONNECT ON DATABASE iot_bridge TO vault_admin;
EOSQL

# Immich vector extensions require schema permissions inside immich DB only
psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "immich" <<EOSQL
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS vchord CASCADE;
CREATE EXTENSION IF NOT EXISTS earthdistance CASCADE;
EOSQL

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "iot_bridge" <<EOSQL
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO iot_rw;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO iot_rw;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO iot_rw;
GRANT iot_rw TO vault_admin WITH ADMIN OPTION;
EOSQL
