#!/usr/bin/env bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<EOSQL
CREATE ROLE releasehub_rw NOLOGIN;
CREATE ROLE svc_keycloak WITH LOGIN PASSWORD '${SVC_KEYCLOAK_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE svc_releasehub WITH LOGIN PASSWORD '${SVC_RELEASEHUB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE IN ROLE releasehub_rw;
CREATE ROLE vault_admin WITH LOGIN PASSWORD '${VAULT_DB_ADMIN_PASSWORD}' CREATEROLE NOSUPERUSER NOCREATEDB;

CREATE DATABASE keycloak OWNER svc_keycloak;
CREATE DATABASE releasehub OWNER pgadmin_pub;

REVOKE ALL ON DATABASE keycloak FROM PUBLIC;
REVOKE ALL ON DATABASE releasehub FROM PUBLIC;

GRANT CONNECT ON DATABASE releasehub TO releasehub_rw;
GRANT CONNECT ON DATABASE releasehub TO vault_admin;
EOSQL

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "releasehub" <<EOSQL
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO releasehub_rw;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO releasehub_rw;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO releasehub_rw;
GRANT releasehub_rw TO vault_admin WITH ADMIN OPTION;
EOSQL
